"""Read-only branch protocol comparison using the same committed local JSONL."""
import ast
from collections import Counter
import hashlib
import json
import math
from numbers import Real
from pathlib import Path
import subprocess

from tensorboard.backend.event_processing.event_accumulator import EventAccumulator

ROOT=Path(__file__).resolve().parents[1]
REF='origin/codex/server-remote-monitor'
REMOTE_PATH='PythonAPI/examples/mappo_training/utils/mut_mappo_tensorboard.py'


def git(*args):
    return subprocess.run(['git',*args],cwd=ROOT,capture_output=True,text=True,encoding='utf-8',check=True).stdout


def build():
    root=ROOT/'experiments/adversarial_u1000_R16_long_20261105_v1'
    replay=root/'analysis/tensorboard_replay_20261105_v1'
    output=root/'analysis/tensorboard_branch_comparison_20261105_v1';output.mkdir(exist_ok=False)
    source=git('show',REF+':'+REMOTE_PATH)
    # Compile only the two pure scalar-projection functions, never its writer/main.
    tree=ast.parse(source)
    functions=[n for n in tree.body if isinstance(n,ast.FunctionDef) and n.name in ('_number','scalar_projection')]
    assert len(functions)==2
    namespace={'Real':Real,'math':math}
    exec(compile(ast.Module(body=functions,type_ignores=[]),'<remote_pure_projection>','exec'),namespace)
    project=namespace['scalar_projection']
    records=[json.loads(x) for x in (root/'runs/R2/metrics.jsonl').read_text(encoding='utf-8').splitlines() if x.strip()]
    boundary=json.loads((root/'runs/R2/checkpoint_manifest.json').read_text(encoding='utf-8'))['completed_round']
    remote_tags={team:set() for team in ('A','B')}
    remote_values={team:{} for team in ('A','B')}
    for row in records:
        if not row.get('teams') or not 0<row['completed_round']<=boundary:continue
        for team,ppo in row['teams'].items():
            payload=dict(ppo=ppo,training_window=row.get('training_window',{}).get(team,{}),
                gate=row.get('gate',{}),cost=row.get('actual_counters',{}),
                meta=dict(completed_round=row['completed_round'],target_updates=row.get('target_updates'),
                    actual_train_ticks=row['actual_counters']['train'],train_tick_budget=row.get('train_tick_budget')))
            projection=dict(project(payload))
            remote_tags[team].update(projection)
            remote_values[team][row['completed_round']]=projection
    local={}
    for directory in (replay/'events').glob('*/*'):
        name=directory.relative_to(replay/'events').as_posix()
        acc=EventAccumulator(str(directory),size_guidance={'scalars':0}).Reload()
        local[name]=set(acc.Tags()['scalars'])
    mapping={'safety/blue_bad_rate':'training_window/b',
        'critical/legacy_event_qualified_rate':'training_window/safe_critical_event',
        'red/both_reached_rate':'training_window/red_success_rate',
        'value/explained_variance':'ppo/explained_variance',
        'value/critic_loss_logged_mean':'ppo/critic_loss/mean',
        'value/absolute_error_logged_mean':'ppo/value_error_abs_mean',
        'value/return_target_std':'ppo/return_target_std'}
    for team in ('A','B'):
        for tag in local['training/'+team]:
            if tag.startswith('reward_component/'):
                mapping[tag]='training_window/reward_components_mean/'+tag.split('/')[-1]
            if tag.startswith('ppo/blue_'):
                _,role,field=tag.split('/');aid=role.split('_')[-1]
                mapping[tag]='ppo/'+field.removesuffix('_logged_mean')+'_'+aid+'/mean'
    data=json.loads((replay/'curve_data.json').read_text(encoding='utf-8'))
    numeric_checks=[]
    for local_tag,remote_tag in sorted(mapping.items()):
        comparisons=[(r['scalars'][local_tag],remote_values[r['team']][r['round']][remote_tag]) for r in data['training']]
        max_error=max(abs(a-b) for a,b in comparisons)
        assert max_error<1e-10,(local_tag,max_error)
        numeric_checks.append(dict(local=local_tag,remote=remote_tag,points=len(comparisons),max_error=max_error))
    result=dict(remote_commit=git('rev-parse',REF).strip(),local_head=git('rev-parse','HEAD').strip(),
        remote_recorder_sha256=hashlib.sha256(source.encode()).hexdigest(),local_event_tags={k:sorted(v) for k,v in local.items()},
        remote_projection_on_LOCAL_logs={k:sorted(v) for k,v in remote_tags.items()},
        remote_category_counts={k:dict(Counter(t.split('/')[0] for t in v)) for k,v in remote_tags.items()},
        exact_numeric_mapping=numeric_checks,
        limitation='Remote tags are generated by the fetched remote projection on the SAME LOCAL committed JSONL, not inspected remote server event files; current remote runs may have new fields.')
    (output/'comparison.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    (output/'remote_recorder_snapshot.py').write_text(source,encoding='utf-8')
    text=['# 本地与远程TensorBoard口径对照','',
        '远程提交：'+result['remote_commit'],'本地HEAD：'+result['local_head']+'（另有当前工作区修改）','',
        result['limitation'],'',
        '当前本地：手工挑选JSONL/episodes及冻结评估的派生回放，training每队52标签、frozen每队约50标签。',
        '远程：MutMAPPOTensorBoard默认随训练启用，投影完整已提交boundary metrics；原始JSONL/checkpoint manifest仍是权威证据。',
        '同一份本地日志按远程规则投影：'+json.dumps({k:len(v) for k,v in remote_tags.items()}),'',
        '横轴：本地回放恒为A+B训练ticks；远程按stop_rule选择rounds时completed_round、否则train ticks。不能直接按横坐标叠图。',
        '列表：远程保留mean/max/item_i，本地仅导出日志均值。',
        '旧training_window/q是安全资格与response（旧响应事件）的交集，不能当作safe_critical_event。',
        '本地特有：从episodes重算团队折扣回报/驾驶测量，以及冻结评估C1/C2完整驾驶与接触前险情指标；远程边界记录器不会自动产生这些派生项。',
        '', '|本地标签|远程对应标签|同日志数值检查|','|---|---|---|']
    for row in numeric_checks:text.append('|`'+row['local']+'`|`'+row['remote']+'`|'+str(row['points'])+'点一致，最大误差'+str(row['max_error'])+'|')
    text.extend(['','|远程类别|A标签数|B标签数|','|---|---:|---:|'])
    for category in sorted(set().union(*(set(x) for x in result['remote_category_counts'].values()))):
        text.append('|'+category+'|'+str(result['remote_category_counts']['A'].get(category,0))+'|'+str(result['remote_category_counts']['B'].get(category,0))+'|')
    (output/'对比说明.md').write_text('\n'.join(text)+'\n',encoding='utf-8')
    print(json.dumps(dict(remote_commit=result['remote_commit'],local_head=result['local_head'],
        remote_projected_tag_counts={k:len(v) for k,v in remote_tags.items()},remote_categories=result['remote_category_counts'],
        matched_tags=len(mapping),numeric_points_verified=sum(r['points'] for r in numeric_checks),output=str(output)),ensure_ascii=False))


if __name__=='__main__':build()
